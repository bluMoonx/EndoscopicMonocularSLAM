"""
Procedure report card: one page that consolidates what Argus measured about a run -- like a
radiology report, but for inspection QUALITY. Computed from the fully-monocular reconstruction
(ftmono mesh + ft trajectory): coverage %, blind regions (count, sizes in mm^2, largest), path
length, and where this withdrawal sits on the speed-vs-coverage curve.

Usage: python speqslam/report_card.py cecum_t1_a   -> results/report_cecum_t1_a.html (+ .json)
"""
import sys, os, glob, json, csv
import numpy as np, cv2, open3d as o3d
from scipy.spatial import cKDTree
from scipy.sparse import csr_matrix
from scipy.sparse.csgraph import connected_components
sys.path.insert(0, "speqslam")
from end2end_coverage import load_poses, coverage_on_mesh, THR

DS = 100.0 / 65535.0 / 1000.0


def analyze(seq):
    undist = f"data/c3vd/{seq}_undist"; K = np.loadtxt(f"{undist}/K.txt")
    h, w = cv2.imread(sorted(glob.glob(f"{undist}/depth01/*.png"))[0], -1).shape[:2]
    mesh = o3d.io.read_triangle_mesh(f"results/mesh/{seq}_ftmono.ply")
    mesh.compute_vertex_normals()
    V = np.asarray(mesh.vertices); N = np.asarray(mesh.vertex_normals)
    T = np.asarray(mesh.triangles)
    poses = load_poses(f"results/c3vd/{seq}_ft.txt")

    a, b = coverage_on_mesh(V, N, poses, K, (h, w))
    cnt = a if a.mean() >= b.mean() else b
    blind = cnt < THR
    # triangle areas (m^2 -> mm^2); a triangle is blind if all 3 vertices are blind
    e1 = V[T[:, 1]] - V[T[:, 0]]; e2 = V[T[:, 2]] - V[T[:, 0]]
    tri_area = 0.5 * np.linalg.norm(np.cross(e1, e2), axis=1) * 1e6
    tri_blind = blind[T].all(1)
    # cluster blind vertices into REGIONS (5mm linkage)
    Vb = V[blind]
    n_reg, sizes_mm2, largest_mm2 = 0, [], 0.0
    if len(Vb) > 3:
        tree = cKDTree(Vb)
        pairs = tree.query_pairs(0.005, output_type="ndarray")
        n = len(Vb)
        adj = csr_matrix((np.ones(len(pairs)), (pairs[:, 0], pairs[:, 1])), shape=(n, n))
        n_reg, lab = connected_components(adj, directed=False)
        # region area: blind-triangle area assigned via its first vertex's region
        vidx = np.full(len(V), -1); vidx[np.where(blind)[0]] = lab
        reg_area = np.zeros(n_reg)
        for t_i in np.where(tri_blind)[0]:
            r = vidx[T[t_i, 0]]
            if r >= 0:
                reg_area[r] += tri_area[t_i]
        sizes_mm2 = sorted([float(x) for x in reg_area if x > 1.0], reverse=True)
        n_reg = len(sizes_mm2)
        largest_mm2 = sizes_mm2[0] if sizes_mm2 else 0.0

    ts = sorted(poses)
    P = np.array([poses[t][:3, 3] for t in ts])
    path_mm = float(np.linalg.norm(np.diff(P, axis=0), axis=1).sum() * 1000)
    dur_s = ts[-1] - ts[0]
    surf_mm2 = float(tri_area.sum())
    blind_mm2 = float(tri_area[tri_blind].sum())
    return dict(seq=seq, n_vertices=int(len(V)), surface_mm2=round(surf_mm2),
                covered_pct=round(100 * (1 - blind_mm2 / max(surf_mm2, 1)), 1),
                blind_pct=round(100 * blind_mm2 / max(surf_mm2, 1), 1),
                blind_regions=n_reg, largest_region_mm2=round(largest_mm2),
                region_sizes_mm2=[round(s) for s in sizes_mm2[:8]],
                path_mm=round(path_mm, 1), duration_s=round(dur_s, 1),
                mean_speed_mm_s=round(path_mm / max(dur_s, 1e-6), 2))


def speed_context(seq):
    try:
        rows = [r for r in csv.DictReader(open("results/withdrawal_speed.csv")) if r["seq"] == seq]
        return [(int(r["speed_x"]), float(r["blind_pct"])) for r in rows]
    except FileNotFoundError:
        return []


