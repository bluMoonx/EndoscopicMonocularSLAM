def main(seq):
    d = analyze(seq)
    speeds = speed_context(seq)
    os.makedirs("results", exist_ok=True)
    json.dump(d, open(f"results/report_{seq}.json", "w"), indent=1)
    open(f"results/report_{seq}.html", "w", encoding="utf-8").write(render(d, speeds))
    print(f"{seq}: covered {d['covered_pct']}%  blind {d['blind_pct']}% in {d['blind_regions']} regions "
          f"(largest {d['largest_region_mm2']}mm2)  -> results/report_{seq}.html", flush=True)


if __name__ == "__main__":
    for s in (sys.argv[1:] or ["cecum_t1_a"]):
        main(s)
